# 1. 扫描项目中所有 .c, .h 文件的真实中文字符与中文标点符号 (BMP 范围)
all_source_chars = set()
for ext in ('main/**/*.c', 'main/**/*.h', 'code/21*/**/*.c', 'code/21*/**/*.h'):
    for path in glob.glob(ext, recursive=True):
        if 'font_' in path:
            continue
        try:
            with open(path, 'r', encoding='utf-8') as f:
                content = f.read()
                matches = re.findall(r'[\u0080-\u00ff\u4e00-\u9fa5\u3000-\u303f\uff00-\uffef\u2000-\u206f\u2100-\u214f]', content)
                for char in matches:
                    all_source_chars.add(char)
        except Exception:
            pass

