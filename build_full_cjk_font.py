all_chars.discard('\r')
all_chars.discard('\t')
all_chars.discard(' ')

symbols_str = "".join(sorted(list(all_chars)))
print(f"Total Unique Symbols: {len(symbols_str)}")

with open("symbols.txt", "w", encoding="utf-8") as f:
    f.write(symbols_str)

# 自动寻找系统可用中文字体 (.ttf 格式)
candidate_fonts = [
    "C:/Windows/Fonts/simhei.ttf",
    "C:/Windows/Fonts/simkai.ttf",
    "C:/Windows/Fonts/simfang.ttf",
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
    "/usr/share/fonts/truetype/wqy/wqy-microhei.ttc"
]

font_path = None
for cp in candidate_fonts:
    if os.path.exists(cp):
        font_path = cp
        break

if not font_path:
    raise RuntimeError("No suitable Chinese TTF font found on system!")

print(f"Using font: {font_path}")

# 直接使用 node 运行 node_modules 里的 lv_font_conv.js
conv_js = os.path.abspath("node_modules/lv_font_conv/lv_font_conv.js")
cmd = [
    "node", conv_js,
    "--size", "14",
    "--bpp", "2",
    "--font", font_path,
    "-r", "0x20-0xFF",
    "--symbols", symbols_str,
    "--format", "lvgl",
    "-o", "main/ui/font_chinese_14.c",
    "--lv-include", "lvgl.h",
    "--lv-font-name", "font_chinese_14"
]

print("Executing lv_font_conv...")
subprocess.run(cmd, check=True)

# 同步到 code/21_final_station_hub/embedded/ui/font_chinese_14.c
